package com.example.tax.model;

import java.sql.Timestamp;

public class OperationLog {

    private long id;
    private Long operatorId;
    private String operatorNameSnapshot;
    private String operationType;
    private String targetType;
    private String targetId;
    private String result;
    private String summary;
    private String traceId;
    private Timestamp createdAt;

    public long getId() {
        return id;
    }

    public void setId(long id) {
        this.id = id;
    }

    public Long getOperatorId() {
        return operatorId;
    }

    public void setOperatorId(Long operatorId) {
        this.operatorId = operatorId;
    }

    public String getOperatorNameSnapshot() {
        return operatorNameSnapshot;
    }

    public void setOperatorNameSnapshot(String operatorNameSnapshot) {
        this.operatorNameSnapshot = operatorNameSnapshot;
    }

    public String getOperationType() {
        return operationType;
    }

    public void setOperationType(String operationType) {
        this.operationType = operationType;
    }

    public String getTargetType() {
        return targetType;
    }

    public void setTargetType(String targetType) {
        this.targetType = targetType;
    }

    public String getTargetId() {
        return targetId;
    }

    public void setTargetId(String targetId) {
        this.targetId = targetId;
    }

    public String getResult() {
        return result;
    }

    public void setResult(String result) {
        this.result = result;
    }

    public String getSummary() {
        return summary;
    }

    public void setSummary(String summary) {
        this.summary = summary;
    }

    public String getTraceId() {
        return traceId;
    }

    public void setTraceId(String traceId) {
        this.traceId = traceId;
    }

    public Timestamp getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Timestamp createdAt) {
        this.createdAt = createdAt;
    }

    public String getResultLabel() {
        return "SUCCESS".equals(result) ? "成功" : "失败";
    }
}
